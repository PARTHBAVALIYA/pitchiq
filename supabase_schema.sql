-- =========================================================================
-- PitchIQ: Supabase Subscribers Table Setup
-- Run this in your Supabase Project -> SQL Editor
-- =========================================================================

-- 1. Create the subscribers table
create table if not exists public.subscribers (
  id bigint generated by default as identity primary key,
  email text unique not null,
  pitch_preview text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Enable Row Level Security (RLS)
alter table public.subscribers enable row level security;

-- 3. Allow anonymous public users to INSERT their emails from the PitchIQ frontend
create policy "Allow anonymous subscribers insert"
  on public.subscribers
  for insert
  with check (true);

-- 4. Allow only service role / authenticated admins to view all subscribers
create policy "Allow authenticated users to read subscribers"
  on public.subscribers
  for select
  using (auth.role() = 'authenticated' or auth.role() = 'service_role');
